def slug(title: str) -> str:
    """Simple Icons' titleToSlug."""
    t = title.lower().replace("+", "plus").replace(".", "dot").replace("&", "and")
    return re.sub(r"[^a-z0-9]", "", unicodedata.normalize("NFD", t))


def companies() -> set[str]:
    names = set()
    for f in (ROOT / "content/paths").glob("*.yaml"):
        names.update(yaml.safe_load(f.read_text()).get("companies") or [])
    for p in yaml.safe_load((ROOT / "content/catalog.yaml").read_text())["problems"]:
        names.update(r["company"] for r in p.get("reports") or [])
    return names - {"Unknown"}


def logos(si: Path) -> dict[str, list[str]]:
    data = json.loads((si / "data/simple-icons.json").read_text())
    by_slug = {d.get("slug") or slug(d["title"]): d for d in data}
    found = {}
    for name in sorted(companies()):
        s = ALIASES.get(name, slug(name))
        svg = si / "icons" / f"{s}.svg"
        if s in by_slug and svg.exists():
            found[name] = [by_slug[s]["hex"], re.search(r' d="([^"]+)"', svg.read_text()).group(1)]
    return found


def icons(lucide: Path) -> dict[str, str]:
    out = {}
    for name in ICONS:
        body = (lucide / "icons" / f"{name}.svg").read_text()
        inner = body[body.index(">", body.index("<svg")) + 1 : body.rindex("</svg>")]
        out[name] = re.sub(r"\s*\n\s*", "", inner).replace(" />", "/>")
    return out


def main() -> None:
    si, lucide = Path(sys.argv[1]), Path(sys.argv[2])
    version = lambda p: json.loads((p / "package.json").read_text())["version"]  # noqa: E731
    found, glyphs = logos(si), icons(lucide)
    OUT.write_text(
        NOTICE.format(si=version(si), lucide=version(lucide))
        + f"const LOGOS = {json.dumps(found, separators=(',', ':'))};\n"
        + f"const ICONS = {json.dumps(glyphs, separators=(',', ':'))};\n"
    )
    print(
        f"Wrote {OUT.relative_to(ROOT)}: {len(found)} of {len(companies())} company logos, {len(glyphs)} icons, {OUT.stat().st_size // 1024} KB"
    )


if __name__ == "__main__":
    main()
